package Calories_and_Counter.practice1;

public class CalorieCounter {

    String name;
    String sex;
    int age;
    double height;
    int weight;


    public CalorieCounter(String name, String sex, int age, int weight, double height) {
        this.name = name;
        this.sex = sex;
        this.age = age;
        this.weight = weight;
        this.height = height;
    }
}
